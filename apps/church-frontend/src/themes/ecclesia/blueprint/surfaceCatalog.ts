export type SurfacePhaseKey = 'I' | 'II' | 'III' | 'IV' | 'V' | 'VI' | 'VII' | 'VIII' | 'IX';
export type SurfaceKind =
  | 'gateway'
  | 'access'
  | 'permission'
  | 'standalone'
  | 'archive'
  | 'detail'
  | 'form'
  | 'portal'
  | 'immersive'
  | 'global'
  | 'state'
  | 'modal';
export type SurfacePlacement = 'header' | 'rail' | 'global' | 'none';
export type SurfaceRenderMode = 'static' | 'blueprint' | 'embedded';

export interface BlueprintField {
  name: string;
  label: string;
  type: 'text' | 'email' | 'tel' | 'number' | 'textarea' | 'select' | 'date' | 'time' | 'checkbox' | 'file';
  required?: boolean;
  options?: string[];
  helper?: string;
}

export interface BlueprintSurface {
  key: string;
  phase: SurfacePhaseKey;
  phaseTitle: string;
  phaseTotal: number;
  phaseItem: string;
  checklistLabel: string;
  title: string;
  slug: string;
  aliases?: string[];
  kind: SurfaceKind;
  placement: SurfacePlacement;
  renderMode: SurfaceRenderMode;
  endpoint: string;
  moduleKey: string;
  summary: string;
  primaryAction: string;
  secondaryAction?: string;
  fields?: BlueprintField[];
  signals?: string[];
  existingTemplate?: string;
}

const PHASE_TITLES: Record<SurfacePhaseKey, string> = {
  I: 'Gateway & Security Surfaces',
  II: 'Core Public-Facing Standalone Pages & Directories',
  III: 'Deep-Tier Templated Post Layouts',
  IV: 'High-Converting Custom Form Pages',
  V: 'Private Member & Discipleship Portals',
  VI: 'Immersive Virtual Spaces',
  VII: 'Global Embedded UI Components',
  VIII: 'Transactional Success & State Screens',
  IX: 'Error, Validation, & Permission Intercept Modals',
};

const PHASE_TOTALS: Record<SurfacePhaseKey, number> = {
  I: 10,
  II: 13,
  III: 7,
  IV: 24,
  V: 5,
  VI: 4,
  VII: 4,
  VIII: 6,
  IX: 15,
};

const defaultSignals = [
  'Tenant scoped request headers',
  'Custom validation states',
  'Draft restore on network loss',
];

function surface(input: Omit<BlueprintSurface, 'phaseTitle' | 'phaseTotal' | 'signals'> & { signals?: string[] }): BlueprintSurface {
  return {
    ...input,
    phaseTitle: PHASE_TITLES[input.phase],
    phaseTotal: PHASE_TOTALS[input.phase],
    signals: input.signals || defaultSignals,
  };
}

