const surfaceBySlug = new Map<string, BlueprintSurface>();

for (const item of SURFACE_CATALOG) {
  surfaceBySlug.set(item.slug, item);
  item.aliases?.forEach((alias) => surfaceBySlug.set(alias, item));
}

export function getBlueprintSurfaceForSlug(slug: string): BlueprintSurface | null {
  return surfaceBySlug.get(slug.replace(/^\/+|\/+$/g, '')) || null;
}

export function shouldRenderBlueprintSurface(slug: string): boolean {
  const surfaceDef = getBlueprintSurfaceForSlug(slug);
  return Boolean(surfaceDef && surfaceDef.renderMode === 'blueprint');
}

export function getPhaseSurfaces(phase: SurfacePhaseKey): BlueprintSurface[] {
  return SURFACE_CATALOG.filter((item) => item.phase === phase);
}

export function getCompletedSurfaceCount(): number {
  return SURFACE_CATALOG.length;
}

